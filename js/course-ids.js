// ============================================================
// FIND COURSE FROM ID
// ============================================================

function findCourseById(enteredId) {

    const id = enteredId.trim().toUpperCase();

    for (const courseKey in COURSE_IDS) {

        if (COURSE_IDS[courseKey].includes(id)) {
            return courseKey;
        }
    }

    return null;
}


// ============================================================
// CHECK ID FOR SPECIFIC COURSE
// ============================================================

function isValidId(courseId, enteredId) {

    if (typeof enteredId !== "string") {
        return false;
    }

    const id = enteredId.trim().toUpperCase();

    if (!COURSE_IDS[courseId]) {
        return false;
    }

    return COURSE_IDS[courseId].includes(id);
}


function isValidCourseId(courseId, enteredId) {
    return isValidId(courseId, enteredId);
}


function getActivatedCourseKeys() {
    let savedKeys = [];

    try {
        const storedKeys = JSON.parse(
            localStorage.getItem("feellk_activated_courses") || "[]"
        );
        let legacyCourses = [];
        try {
            legacyCourses = JSON.parse(
                localStorage.getItem("feelLK_my_courses") || "[]"
            );
        } catch (error) {
            legacyCourses = [];
        }

        if (Array.isArray(storedKeys)) {
            savedKeys = storedKeys.filter(
                (courseKey, index) => COURSE_IDS[courseKey] && storedKeys.indexOf(courseKey) === index
            );
        }

        if (Array.isArray(legacyCourses)) {
            legacyCourses.forEach(course => {
                if (
                    course &&
                    isValidId(course.courseId, course.accessId) &&
                    !savedKeys.includes(course.courseId)
                ) {
                    savedKeys.push(course.courseId);
                }
            });
        }

        localStorage.setItem(
            "feellk_activated_courses",
            JSON.stringify(savedKeys)
        );
    } catch (error) {
        return [];
    }

    return savedKeys;
}